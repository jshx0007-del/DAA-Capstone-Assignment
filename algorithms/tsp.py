"""
algorithms/tsp.py
Manual Nearest Neighbor TSP Approximation Algorithm for delivery route generation.

Problem:
Given a warehouse (depot) and a set of selected delivery locations, find a closed-loop
or open-loop route that starts at the warehouse, visits every customer location at least once,
and returns to the warehouse while minimizing total travel distance.

TSP is NP-Hard. Nearest Neighbor is a Greedy Heuristic:
- In each step, the delivery van chooses the nearest reachable unvisited customer location.
- Time Complexity: O(k^2 + k * (V + E) log V) where k is the number of delivery stops,
  utilizing Dijkstra's shortest paths between stops.
- Approximation Guarantee: Greedy choice can get trapped into expensive return legs.
  It does not guarantee the global optimal route, but provides a practical O(k^2)
  approximation suitable for real-time logistics planning.
"""

import time
from typing import List, Dict, Any, Optional
from models.delivery_graph import DeliveryGraph
from algorithms.dijkstra import dijkstra_shortest_paths, DijkstraResult


class RouteLeg:
    """Represents a single segment between two consecutive stops in the TSP route."""

    def __init__(
        self,
        from_node: str,
        to_node: str,
        distance_km: float,
        path: List[str]
    ):
        self.from_node = from_node
        self.to_node = to_node
        self.distance_km = distance_km
        self.path = path

    def to_dict(self) -> Dict[str, Any]:
        return {
            "from": self.from_node,
            "to": self.to_node,
            "distance_km": round(self.distance_km, 2),
            "path": self.path,
            "path_str": " -> ".join(self.path)
        }


class TSPResult:
    """Encapsulates the complete delivery route generated by Nearest Neighbor."""

    def __init__(
        self,
        warehouse: str,
        route_sequence: List[str],
        detailed_legs: List[RouteLeg],
        total_distance_km: float,
        full_expanded_path: List[str],
        unreachable_stops: List[str],
        execution_time: float,
        is_closed_tour: bool
    ):
        self.warehouse = warehouse
        self.route_sequence = route_sequence
        self.detailed_legs = detailed_legs
        self.total_distance_km = total_distance_km
        self.full_expanded_path = full_expanded_path
        self.unreachable_stops = unreachable_stops
        self.execution_time = execution_time
        self.is_closed_tour = is_closed_tour

    def summary(self) -> Dict[str, Any]:
        return {
            "warehouse": self.warehouse,
            "stops_count": len(self.route_sequence) - (2 if self.is_closed_tour else 1),
            "route_sequence": self.route_sequence,
            "total_distance_km": round(self.total_distance_km, 2),
            "is_closed_tour": self.is_closed_tour,
            "unreachable_stops": self.unreachable_stops,
            "execution_time_ms": self.execution_time * 1000
        }


def solve_tsp_nearest_neighbor(
    graph: DeliveryGraph,
    warehouse: str,
    delivery_locations: List[str]
) -> TSPResult:
    """
    Executes manual Nearest Neighbor TSP Approximation.

    Algorithm Steps:
    1. Filter unique delivery locations (excluding the warehouse depot itself).
    2. Maintain a set of unvisited locations.
    3. Start current_node = warehouse.
    4. While unvisited locations exist:
       a. Run Dijkstra from current_node (or use precomputed distances).
       b. Select the unvisited node with minimal shortest-path distance.
       c. If unreachable, record as unreachable and break.
       d. Advance to selected node, append to route, accumulate distance.
    5. Attempt to return from the last visited node back to the warehouse.
    6. Return complete structured TSPResult with detailed turn-by-turn road paths.

    Args:
        graph: DeliveryGraph instance.
        warehouse: Name of the depot (start and end location).
        delivery_locations: List of locations to deliver to.

    Returns:
        TSPResult with sequence, total distance, legs, and runtime.
    """
    start_time = time.perf_counter()

    # Clean and deduplicate target locations (preserving order of appearance)
    unique_targets: List[str] = []
    seen = set()
    for loc in delivery_locations:
        if loc != warehouse and loc not in seen:
            seen.add(loc)
            unique_targets.append(loc)

    # Edge case: No delivery locations
    if not unique_targets:
        elapsed = time.perf_counter() - start_time
        return TSPResult(
            warehouse=warehouse,
            route_sequence=[warehouse],
            detailed_legs=[],
            total_distance_km=0.0,
            full_expanded_path=[warehouse],
            unreachable_stops=[],
            execution_time=elapsed,
            is_closed_tour=True
        )

    # Initialize tour state
    route_sequence = [warehouse]
    detailed_legs: List[RouteLeg] = []
    full_expanded_path: List[str] = [warehouse]
    unvisited = set(unique_targets)
    current_node = warehouse
    total_distance = 0.0
    unreachable_stops: List[str] = []

    # Greedy Nearest Neighbor loop
    while unvisited:
        # Run Dijkstra from current_node to find shortest paths to all candidates
        dijkstra_res = dijkstra_shortest_paths(graph, current_node)

        nearest_node: Optional[str] = None
        min_dist = float("inf")

        for candidate in unvisited:
            cand_dist = dijkstra_res.get_distance_to(candidate)
            if cand_dist < min_dist:
                min_dist = cand_dist
                nearest_node = candidate

        # If remaining nodes cannot be reached from current_node
        if nearest_node is None or min_dist == float("inf"):
            unreachable_stops.extend(list(unvisited))
            break

        # Leg path
        leg_path = dijkstra_res.get_path_to(nearest_node) or [current_node, nearest_node]
        leg = RouteLeg(
            from_node=current_node,
            to_node=nearest_node,
            distance_km=min_dist,
            path=leg_path
        )
        detailed_legs.append(leg)

        # Extend expanded path (excluding first node to prevent duplicates in chaining)
        full_expanded_path.extend(leg_path[1:])

        total_distance += min_dist
        route_sequence.append(nearest_node)
        unvisited.remove(nearest_node)
        current_node = nearest_node

    # Return leg to warehouse
    is_closed_tour = False
    if current_node != warehouse and not unreachable_stops:
        return_dijkstra = dijkstra_shortest_paths(graph, current_node)
        return_dist = return_dijkstra.get_distance_to(warehouse)

        if return_dist != float("inf"):
            return_path = return_dijkstra.get_path_to(warehouse) or [current_node, warehouse]
            return_leg = RouteLeg(
                from_node=current_node,
                to_node=warehouse,
                distance_km=return_dist,
                path=return_path
            )
            detailed_legs.append(return_leg)
            full_expanded_path.extend(return_path[1:])
            total_distance += return_dist
            route_sequence.append(warehouse)
            is_closed_tour = True

    elapsed = time.perf_counter() - start_time

    return TSPResult(
        warehouse=warehouse,
        route_sequence=route_sequence,
        detailed_legs=detailed_legs,
        total_distance_km=total_distance,
        full_expanded_path=full_expanded_path,
        unreachable_stops=unreachable_stops,
        execution_time=elapsed,
        is_closed_tour=is_closed_tour
    )

